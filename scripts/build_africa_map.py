"""Build the explorer's Africa outline from Natural Earth (public domain).

    python scripts/build_africa_map.py path/to/ne_50m_admin_0_countries.geojson

Writes src/virotrace/export/africa_map.py: one SVG path per country, projected with a
Lambert azimuthal equal-area projection centred on Africa, rings simplified to about 0.05
degrees, tiny islets dropped (the largest ring of every country is always kept). Run once;
the output is committed so the site build needs no network and no GIS library.
Natural Earth: https://www.naturalearthdata.com/ (public domain).
"""

import json
import math
import sys
from pathlib import Path

LON0, LAT0 = 20.0, 2.0
TOLERANCE = 0.05  # degrees
MIN_RING_EXTENT = 0.35  # degrees; smaller rings are dropped unless they are a country's largest
WIDTH = 760.0


def laea(lon: float, lat: float) -> tuple[float, float]:
    lam, phi, lam0, phi0 = (math.radians(v) for v in (lon, lat, LON0, LAT0))
    k = math.sqrt(
        2
        / (
            1
            + math.sin(phi0) * math.sin(phi)
            + math.cos(phi0) * math.cos(phi) * math.cos(lam - lam0)
        )
    )
    x = k * math.cos(phi) * math.sin(lam - lam0)
    y = k * (math.cos(phi0) * math.sin(phi) - math.sin(phi0) * math.cos(phi) * math.cos(lam - lam0))
    return x, -y


def rdp(points: list[tuple[float, float]], eps: float) -> list[tuple[float, float]]:
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy)
    far, idx = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = (
            math.hypot(px - x1, py - y1)
            if norm == 0
            else abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        )
        if d > far:
            far, idx = d, i
    if far <= eps:
        return [points[0], points[-1]]
    return rdp(points[: idx + 1], eps)[:-1] + rdp(points[idx:], eps)


def main() -> None:
    src = Path(sys.argv[1])
    gj = json.loads(src.read_text())
    feats = []
    for f in gj["features"]:
        p = f["properties"]
        if p.get("CONTINENT") != "Africa" and p.get("ISO_A3_EH") not in {"ESH"}:
            continue
        geom = f["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        rings = [poly[0] for poly in polys]
        lons = [pt[0] for r in rings for pt in r]
        lats = [pt[1] for r in rings for pt in r]
        clon, clat = sum(lons) / len(lons), sum(lats) / len(lats)
        if not (-20 < clon < 62 and -37 < clat < 38):
            continue  # Cabo Verde and other outliers that would stretch the frame
        feats.append((p, rings))
    # project to a common frame first, so the scale is shared by every country
    proj = [(p, [[laea(*pt) for pt in r] for r in rings], rings) for p, rings in feats]
    xs = [x for _, rs, _ in proj for r in rs for x, _ in r]
    ys = [y for _, rs, _ in proj for r in rs for _, y in r]
    x0, y0 = min(xs), min(ys)
    scale = WIDTH / (max(xs) - x0)
    height = (max(ys) - y0) * scale
    deg = scale * math.radians(1)  # px per degree at the centre
    out = []
    for p, prings, lonlat in proj:
        extents = [
            max(
                max(a for a, _ in r) - min(a for a, _ in r),
                max(b for _, b in r) - min(b for _, b in r),
            )
            for r in lonlat
        ]
        biggest = extents.index(max(extents))
        parts = []
        cx = cy = 0.0
        for i, r in enumerate(prings):
            if extents[i] < MIN_RING_EXTENT and i != biggest:
                continue
            pts = [((x - x0) * scale, (y - y0) * scale) for x, y in r]
            pts = rdp(pts, TOLERANCE * deg)
            if len(pts) < 3:
                continue
            parts.append("M" + "L".join(f"{a:.1f},{b:.1f}" for a, b in pts) + "Z")
            if i == biggest:
                cx = sum(a for a, _ in pts) / len(pts)
                cy = sum(b for _, b in pts) / len(pts)
        names = sorted(
            {p[k] for k in ("NAME", "NAME_LONG", "ADMIN", "NAME_EN", "FORMAL_EN") if p.get(k)}
        )
        out.append(
            {
                "id": p.get("ISO_A3_EH") if p.get("ISO_A3_EH") not in (None, "-99") else p["ADMIN"],
                "name": p["NAME"],
                "names": names,
                "d": "".join(parts),
                "cx": round(cx, 1),
                "cy": round(cy, 1),
            }
        )
    out.sort(key=lambda f: f["id"])
    payload = {"width": WIDTH, "height": round(height, 1), "features": out}
    target = Path("src/virotrace/export/africa_map.py")
    target.write_text(
        '"""Africa outline for the explorer, generated by scripts/build_africa_map.py.\n\n'
        'Natural Earth 1:50m admin-0 countries (public domain), projected and simplified.\n"""\n\n'
        "import json\n\n"
        f'AFRICA = json.loads(\n    r"""{json.dumps(payload, ensure_ascii=False, separators=(",", ":"))}"""\n)\n'
    )
    print(
        f"{len(out)} countries, {target.stat().st_size / 1024:.0f} kB, frame {WIDTH} x {height:.0f}"
    )


if __name__ == "__main__":
    main()
