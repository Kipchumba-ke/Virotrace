"""Turn a transcribed WHO SDRM table into the ``sdrm_who.tsv`` the pipeline loads.

The authoritative list is a published table, so the human step is copying it out. This
module makes that step checkable: it refuses tokens it cannot read (never silently
dropping one) and can compare every wild-type residue with the HXB2 protein, which
catches most transcription typos.

Accepted input, one class per line, any mix of separators::

    NRTI: M41L, K65R, K70R, L74V/I, T69D/Ins/Del
    PI: M46IL, I47VA

Insertions and deletions (``/Ins``, ``/Del``) are not amino-acid substitutions. They are
kept in their own column and never mixed into ``residues``: reading "Ins" as the
residues I, N and S would silently tag the wrong mutations.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass

from ..errors import ContractError

CLASS_TO_GENE = {"NRTI": "RT", "NNRTI": "RT", "PI": "PR", "INSTI": "IN"}
_CLASS_LINE = re.compile(r"^\s*(NNRTI|NRTI|INSTI|PI)s?\b\s*[:\-]?\s*(.*)$", re.IGNORECASE)
_TOKEN = re.compile(r"^([A-Z])(\d{1,3})([A-Z/]+)$")
_INDEL = re.compile(r"/(Ins|Del)\b")
_AMINO_ACIDS = set("ACDEFGHIKLMNPQRSTVWY")


@dataclass(frozen=True, slots=True)
class SdrmRow:
    drug_class: str
    gene: str
    position: int
    wild_type: str
    residues: str  # sorted, deduplicated one-letter codes
    indels: str = ""  # any of "Del", "Ins", comma-separated, sorted


def parse_sdrm_text(text: str) -> list[SdrmRow]:
    rows: dict[tuple[str, str, int], SdrmRow] = {}
    current: str | None = None
    unreadable: list[str] = []

    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = _CLASS_LINE.match(line)
        if match:
            current = match.group(1).upper()
            line = match.group(2)
        if current is None:
            raise ContractError(
                f"mutation text before any class header (NRTI/NNRTI/PI/INSTI): {raw!r}"
            )
        for token in re.split(r"[,;\s]+", line):
            if not token:
                continue
            indels = set(_INDEL.findall(token))
            token = _INDEL.sub("", token)
            parsed = _TOKEN.match(token.upper())
            if parsed is None:
                unreadable.append(f"{current}: {token!r}")
                continue
            wild_type, position, residues = parsed.group(1), int(parsed.group(2)), parsed.group(3)
            letters = {c for c in residues if c != "/"}
            if wild_type not in _AMINO_ACIDS or not letters <= _AMINO_ACIDS:
                unreadable.append(f"{current}: {token!r}")
                continue
            key = (current, CLASS_TO_GENE[current], position)
            previous = rows.get(key)
            merged = letters | set(previous.residues) if previous else letters
            if previous and previous.indels:
                indels |= set(previous.indels.split(","))
            rows[key] = SdrmRow(
                current,
                key[1],
                position,
                wild_type,
                "".join(sorted(merged)),
                ",".join(sorted(indels)),
            )

    if unreadable:
        raise ContractError(
            "unreadable SDRM tokens (fix the text, nothing was dropped): " + "; ".join(unreadable)
        )
    if not rows:
        raise ContractError("no mutations found in SDRM text")
    return sorted(rows.values(), key=lambda r: (r.gene, r.position, r.drug_class))


def check_wild_types(rows: list[SdrmRow], proteins: dict[str, str]) -> list[str]:
    """Describe every row whose wild-type residue differs from the reference protein.

    Advisory, not fatal: HXB2 differs from the subtype B consensus at a few positions,
    so a mismatch is a prompt to re-read the source table, not proof of an error.
    """
    problems: list[str] = []
    for row in rows:
        protein = proteins.get(row.gene)
        if protein is None or not 1 <= row.position <= len(protein):
            problems.append(f"{row.gene}{row.position}: outside the reference protein")
        elif protein[row.position - 1] != row.wild_type:
            problems.append(
                f"{row.gene}:{row.wild_type}{row.position}{row.residues} but HXB2 has "
                f"{protein[row.position - 1]} at {row.position}"
            )
    return problems


def render_tsv(rows: list[SdrmRow], *, source: str, version: str, input_text: str) -> str:
    digest = hashlib.sha256(input_text.encode()).hexdigest()[:16]
    header = [
        f"# WHO surveillance drug resistance mutation list, version {version}",
        f"# Source: {source}",
        f"# Transcribed text sha256 (first 16): {digest}",
        "# Generated by scripts/sdrm_from_text.py; edit the source text, not this file.",
        "gene\tposition\tresidues\tindels",
    ]
    body = [f"{r.gene}\t{r.position}\t{r.residues}\t{r.indels}" for r in rows]
    return "\n".join(header + body) + "\n"
